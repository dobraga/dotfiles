export function iconColor(n: FileNode): string | undefined {
  const lower = n.name.toLowerCase()
  if (n.kind === 'dir') return DIR_COLORS[lower]
  const named = NAME_COLORS[lower] ?? (lower.startsWith('.env') ? NAME_COLORS['.env'] : undefined)
  if (named) return named
  const dot = lower.lastIndexOf('.')
  return dot >= 0 ? EXT_COLORS[lower.slice(dot + 1)] : undefined
}

