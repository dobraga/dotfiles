// Generates icons/ and icon-map.js from a checkout of
// https://github.com/material-extensions/vscode-material-icon-theme (MIT).
// Usage: node scripts/gen-icons.mjs <path-to-upstream-checkout>
// Last generated from upstream commit 3bf5135d7cb7c41ffcd1c60c5f6afdb6c6e6cc41.
import { readFileSync, writeFileSync, copyFileSync, mkdirSync, existsSync, readdirSync, rmSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const upstream = process.argv[2];
if (!upstream) throw new Error("usage: node gen-icons.mjs <upstream-checkout>");
const here = dirname(fileURLToPath(import.meta.url));
const out = join(here, "..");

// The tables are plain object literals except for a few `FileNamePattern.X` enum refs inside
// `patterns:`; stub the enum and evaluate the array text.
function extractArray(src, startMarker) {
  const start = src.indexOf(startMarker);
  if (start < 0) throw new Error(`marker not found: ${startMarker}`);
  let i = src.indexOf("[", start);
  const begin = i;
  let depth = 0;
  let quote = null;
  for (; i < src.length; i++) {
    const c = src[i];
    if (quote) {
      if (c === "\\") i++;
      else if (c === quote) quote = null;
    } else if (c === "'" || c === '"' || c === "`") quote = c;
    else if (c === "[") depth++;
    else if (c === "]" && --depth === 0) break;
  }
  const FileNamePattern = new Proxy({}, { get: () => "" });
  const IconPack = new Proxy({}, { get: () => "" });
  return new Function("FileNamePattern", "IconPack", `return ${src.slice(begin, i + 1)}`)(FileNamePattern, IconPack);
}

const filesSrc = readFileSync(join(upstream, "src/core/icons/fileIcons.ts"), "utf8");
const foldersSrc = readFileSync(join(upstream, "src/core/icons/folderIcons.ts"), "utf8");
const fileDefs = extractArray(filesSrc, "parseByPattern(");
const folderDefs = extractArray(foldersSrc, "icons: [");

const ext = {};
const names = {};
const folders = {};
const used = new Set(["document", "folder-base"]);
const have = (n) => existsSync(join(upstream, "icons", `${n}.svg`));
const read = (n) => readFileSync(join(upstream, "icons", `${n}.svg`), "utf8");

// Upstream builds the open-folder variants (and the default file/folder icons) at build time
// (src/scripts/svg/generateOpenFolderIcons.ts); do the same here without running its build.
const OPEN_FOLDER_PATH =
  "M14.483 6H4.721a1 1 0 0 0-.949.684L2 12V5h12a1 1 0 0 0-1-1H7.562a1 1 0 0 1-.64-.232l-.644-.536A1 1 0 0 0 5.638 3H2a1 1 0 0 0-1 1v8a1 1 0 0 0 1 1h11l2.403-5.606A1 1 0 0 0 14.483 6";
function openVariant(svg) {
  if (!svg.includes('viewBox="0 0 16 16"') || !/<path[^>]*id="folder"/.test(svg)) return null;
  return svg.replace(/(<path[^>]*id="folder"[^>]*\sd=")[^"]*(")/, `$1${OPEN_FOLDER_PATH}$2`).replace(/(<path[^>]*\sd=")[^"]*("[^>]*id="folder")/, `$1${OPEN_FOLDER_PATH}$2`);
}

for (const d of fileDefs) {
  if (!d.name || !have(d.name)) continue;
  for (const e of d.fileExtensions ?? []) ext[e.toLowerCase()] = d.name;
  for (const n of d.fileNames ?? []) names[n.toLowerCase()] = d.name;
  used.add(d.name);
}
for (const d of folderDefs) {
  if (!d.name || !have(d.name)) continue;
  for (const n of d.folderNames ?? []) folders[n.toLowerCase()] = d.name;
  used.add(d.name);
}

const dest = join(out, "icons");
mkdirSync(dest, { recursive: true });
for (const f of readdirSync(dest)) if (f.endsWith(".svg")) rmSync(join(dest, f));
const openOf = {};
for (const n of used) {
  if (!have(n)) continue;
  copyFileSync(join(upstream, "icons", `${n}.svg`), join(dest, `${n}.svg`));
  if (n.startsWith("folder-")) {
    const open = openVariant(read(n));
    if (open) {
      writeFileSync(join(dest, `${n}-open.svg`), open);
      openOf[n] = 1;
    }
  }
}
// Defaults the theme names "file" / "folder" / "folder-open".
copyFileSync(join(dest, "document.svg"), join(dest, "file.svg"));
copyFileSync(join(dest, "folder-base.svg"), join(dest, "folder.svg"));
copyFileSync(join(dest, "folder-base-open.svg"), join(dest, "folder-open.svg"));
copyFileSync(join(upstream, "LICENSE"), join(dest, "LICENSE"));

const hasOpen = openOf;
writeFileSync(
  join(out, "icon-map.js"),
  `// GENERATED by scripts/gen-icons.mjs from material-extensions/vscode-material-icon-theme (MIT). Do not edit.\n` +
    `export const EXT = ${JSON.stringify(ext)};\n` +
    `export const NAMES = ${JSON.stringify(names)};\n` +
    `export const FOLDERS = ${JSON.stringify(folders)};\n` +
    `export const HAS_OPEN = ${JSON.stringify(hasOpen)};\n`,
);
// tabs-folders shows the same icons in the tab bar. Mods are loaded from separate directories, so
// it gets its own copy of the lookup instead of a cross-mod import (icon files are shared by path).
const tabsDir = join(out, "..", "tabs-folders");
copyFileSync(join(out, "icon-map.js"), join(tabsDir, "icon-map.js"));
copyFileSync(join(out, "icon-for.js"), join(tabsDir, "icon-for.js"));
console.log(`icons: ${used.size}, ext: ${Object.keys(ext).length}, names: ${Object.keys(names).length}, folders: ${Object.keys(folders).length}`);
